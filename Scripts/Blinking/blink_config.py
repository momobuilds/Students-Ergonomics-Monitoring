# =============================================================================
# DATA COLLECTION SETTINGS  (mirrors TRAINING_COLLECTION_DURATION in posture)
# =============================================================================

# Duration of each data-collection phase (Normal / Tired) in seconds.
TRAINING_COLLECTION_DURATION = 60   # 1 minute per class

# =============================================================================
# EAR / BLINK DETECTION THRESHOLDS
# =============================================================================

# Eye Aspect Ratio below this value → eye is considered closed.
EAR_CLOSED_THRESHOLD = 0.21

# A blink must last at least this many consecutive closed-eye frames.
MIN_BLINK_FRAMES = 2

# If eyes stay closed longer than this it is NOT counted as a normal blink.
MAX_BLINK_SECONDS = 1.0

# =============================================================================
# METRICS & ALERT SETTINGS
# =============================================================================

# Rolling window for blink frequency and PERCLOS computation.
METRICS_WINDOW_SECONDS = 60.0

# PERCLOS threshold: fraction of time with closed eyes → "bad".
PERCLOS_BAD_THRESHOLD = 0.20

# Blinks per minute — below this may indicate visual fatigue / staring.
MIN_BLINKS_PER_MINUTE = 10.0

# Alert is raised only if poor blinking metrics persist this long.
LOW_BLINK_ALERT_SECONDS    = 120.0
HIGH_PERCLOS_ALERT_SECONDS = 30.0

# =============================================================================
# LOGGING
# =============================================================================

# Periodic CSV logging interval (seconds).
CSV_LOG_INTERVAL_SECONDS = 60.0

